#ifndef PIN_CONFIG_H
#define PIN_CONFIG_H

// ================================================================
// 引脚集中配置
// ================================================================
// ──────────────────────────────────────────────────────────────
// 电机引脚（4 个直流电机）
// 每个电机 3 个引脚：IN1(方向A)、IN2(方向B)、PWM(速度)
// ──────────────────────────────────────────────────────────────
#define MOTOR1_IN1   7
#define MOTOR1_IN2   15
#define MOTOR1_PWM   16

#define MOTOR2_IN1   40
#define MOTOR2_IN2   41
#define MOTOR2_PWM   39

#define MOTOR3_IN1   2
#define MOTOR3_IN2   42
#define MOTOR3_PWM   1

#define MOTOR4_IN1   5
#define MOTOR4_IN2   6
#define MOTOR4_PWM   4

// ──────────────────────────────────────────────────────────────
// 编码器引脚（AB 相正交编码器）
// ──────────────────────────────────────────────────────────────
#define ENCODER0_A   3
#define ENCODER0_B   8

#define ENCODER1_A   48
#define ENCODER1_B   36

#define ENCODER2_A   38
#define ENCODER2_B   37

#define ENCODER3_A   17
#define ENCODER3_B   18

// ──────────────────────────────────────────────────────────────
// SSD1306 OLED 屏幕 (I2C)
//   默认地址 0x3C
// ──────────────────────────────────────────────────────────────
#define OLED_SDA     48
#define OLED_SCL     47

// ──────────────────────────────────────────────────────────────
// HC-SR04 超声波测距
// ──────────────────────────────────────────────────────────────
#define SONIC_TRIG   13
#define SONIC_ECHO   45

// ──────────────────────────────────────────────────────────────
// MPU6050 姿态传感器 (I2C)
// ──────────────────────────────────────────────────────────────
#define MPU_SDA      9
#define MPU_SCL      46

// ──────────────────────────────────────────────────────────────
// ST7735 TFT 屏幕 (SPI — 软件 SPI)
// ──────────────────────────────────────────────────────────────
#define TFT_SCLK     11   // SPI 时钟
#define TFT_MOSI     12   // SPI 数据
#define TFT_CS       21   // 片选
#define TFT_DC       14   // 数据/命令
#define TFT_RST      13   // 复位

// ──────────────────────────────────────────────────────────────
// 舵机（云台）
// ──────────────────────────────────────────────────────────────
#define SERVO_PAN    18
#define SERVO_TILT   17

// ──────────────────────────────────────────────────────────────
// 配网按钮（GPIO44 按键接地 → 清空配置并进入配网模式）
// ──────────────────────────────────────────────────────────────
#define CFG_BUTTON   44

#endif // PIN_CONFIG_H
